// Copies shared protocol assets into the Flutter app and generates Dart design tokens.
//
//   dart run tool/sync_protocol.dart
//
// Sources (single source of truth, shared with desktop and server):
//   ../protocol/effects/catalog.json -> assets/protocol/catalog.json
//   ../protocol/design/tokens.json   -> lib/theme/tokens.g.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final root = File.fromUri(Platform.script).parent.parent;
  final protocol = Directory('${root.path}/../protocol');

  final assets = Directory('${root.path}/assets/protocol')..createSync(recursive: true);
  File('${protocol.path}/effects/catalog.json').copySync('${assets.path}/catalog.json');

  final tokens = jsonDecode(File('${protocol.path}/design/tokens.json').readAsStringSync()) as Map<String, dynamic>;
  File('${root.path}/lib/theme/tokens.g.dart').writeAsStringSync(_generateTokens(tokens));

  stdout.writeln('synced catalog and tokens from ${protocol.path}');
}

String _color(String hex) {
  final h = hex.substring(1);
  final rgb = h.substring(0, 6).toUpperCase();
  final alpha = h.length == 8 ? h.substring(6).toUpperCase() : 'FF';
  return 'Color(0x$alpha$rgb)';
}

String _generateTokens(Map<String, dynamic> t) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/sync_protocol.dart from protocol/design/tokens.json. Do not edit.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('abstract final class LumioColors {');
  (t['color'] as Map<String, dynamic>).forEach((k, v) => b.writeln('  static const $k = ${_color(v as String)};'));
  b
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class LumioRadius {');
  (t['radius'] as Map<String, dynamic>).forEach((k, v) => b.writeln('  static const double $k = $v;'));
  b
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class LumioSpace {');
  (t['space'] as Map<String, dynamic>).forEach((k, v) => b.writeln('  static const double $k = $v;'));
  final motion = t['motion'] as Map<String, dynamic>;
  final easing = (motion['easing'] as List).join(', ');
  b
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class LumioMotion {')
    ..writeln('  static const fast = Duration(milliseconds: ${motion['durationFast']});')
    ..writeln('  static const base = Duration(milliseconds: ${motion['durationBase']});')
    ..writeln('  static const slow = Duration(milliseconds: ${motion['durationSlow']});')
    ..writeln('  static const easing = <double>[$easing];')
    ..writeln('}');
  return b.toString();
}
