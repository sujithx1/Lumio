/**
 * Generates src/styles/tokens.generated.css (a Tailwind v4 @theme block) from protocol/design/tokens.json,
 * so desktop and mobile share one source of design tokens. Runs before dev/build/typecheck.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const tokens = JSON.parse(readFileSync(join(root, "../protocol/design/tokens.json"), "utf8"));

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
// "text*" would produce awkward classes like text-text-muted; expose them as fg-*.
const colorName = (k: string) => kebab(k.replace(/^text/, "fg")).replace(/^fg-$/, "fg");

const lines: string[] = [];
for (const [k, v] of Object.entries<string>(tokens.color)) lines.push(`  --color-${colorName(k)}: ${v};`);
for (const [k, v] of Object.entries<number>(tokens.radius)) lines.push(`  --radius-${k}: ${v}px;`);
lines.push(
  `  --font-sans: "${tokens.font.family}", ui-sans-serif, -apple-system, BlinkMacSystemFont, "Segoe UI", system-ui, sans-serif;`,
  `  --font-mono: "${tokens.font.monoFamily}", ui-monospace, SFMono-Regular, Menlo, monospace;`,
  `  --ease-synq: cubic-bezier(${tokens.motion.easing.join(", ")});`,
  `  --duration-fast: ${tokens.motion.durationFast}ms;`,
  `  --duration-base: ${tokens.motion.durationBase}ms;`,
  `  --duration-slow: ${tokens.motion.durationSlow}ms;`,
);

const css = `/* Generated by scripts/sync-tokens.ts from protocol/design/tokens.json. Do not edit. */\n@theme {\n${lines.join("\n")}\n}\n`;
writeFileSync(join(root, "src/styles/tokens.generated.css"), css);
